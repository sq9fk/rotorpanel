# Osmy wiersz maja tylko ogonki.
OGONKI = {"g": 0x0E, "j": 0x0C, "p": 0x10, "q": 0x01, "y": 0x0E, ",": 0x08, ";": 0x00}

# Komorki zrzutu, ktore na pewno pokazuja to samo co ramka: napisy stale.
PEWNE = {1: range(20, 40), 2: range(20, 40), 3: range(20, 40),
         4: range(15, 24), 6: range(0, 40)}


def zmierzone(zrzut, ramka_plik, szer, wys, stride):
    """Glify wyciete ze zrzutu - ta sama arytmetyka siatki co przy kafelkach."""
    import importlib.util
    sciezka = os.path.join(K, "ucz-kafelki.py")
    stare = sys.argv
    sys.argv = ["ucz", zrzut, ramka_plik, str(szer), str(wys), str(stride),
                os.path.join(K, "..", "obj", "czcionka-nieuzywane.cs")]
    spec = importlib.util.spec_from_file_location("ucz", sciezka)
    ucz = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ucz)
    sys.argv = stare

    wynik = {}
    for w, zakres in PEWNE.items():
        for k in zakres:
            kod = ucz.ramka[5 + w * 40 + k]
            if 0x01 <= kod <= 0x5F:
                wynik[chr(kod + 0x20)] = ucz.komorka(w, k)
    return wynik


def z_klasycznej(znak):
    # 0x5F to na panelu znak wypelnienia (kursor), nie ASCII 0x7F
    wiersze = list(KLASYCZNA.get(znak, (0x1F,) * 7))
    wiersze.append(OGONKI.get(znak, 0x00))
    return tuple(wiersze)


ZRZUT = sys.argv[1:6] if len(sys.argv) > 5 else None
WYJSCIE = sys.argv[6] if len(sys.argv) > 6 else (
    sys.argv[1] if len(sys.argv) == 2 else os.path.join(K, "..", "CzcionkaSpe.cs"))

pomiar = {}
if ZRZUT:
    pomiar = zmierzone(ZRZUT[0], ZRZUT[1], int(ZRZUT[2]), int(ZRZUT[3]), int(ZRZUT[4]))
    rozne = [z for z in sorted(pomiar) if z in KLASYCZNA and pomiar[z] != z_klasycznej(z)]
    print("zmierzonych znakow: %d, roznych od klasycznej: %d  %s" %
          (len(pomiar), len(rozne), " ".join(repr(z) for z in rozne)))

linie = []
for kod in range(0x60):
    znak = chr(kod + 0x20)
    mapa = pomiar.get(znak) or z_klasycznej(znak)
    skad = "zmierzone" if znak in pomiar else "klasyczna"
    linie.append("        /* 0x%02X %-3s %s */ new byte[] { %s }," % (
        kod, repr(znak).replace("'", "").replace('"', "") or " ", skad,
        ", ".join("0x%02X" % w for w in mapa)))

